import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync, symlinkSync, readlinkSync, realpathSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {configure} from '../src/adapter.ts';
import {createSnapshot, inspectClone, validateCreate} from '../src/clone.ts';
import {cloneReview, setCloneWorldEnabled} from '../src/clone-review.ts';
import {json, writeJson} from '../src/io.ts';
import {EMPTY_COPY, type CreateInput} from '../src/types.ts';

test('complete clone preserves unknown plugin data without Bot copy rules', async () => {
    const root = mkdtempSync(join(tmpdir(), 'manager-clone-'));
    const home = join(root, 'deployments'), src = join(home, 'source');
    mkdirSync(join(root, 'official/bin'), {recursive:true});
    writeFileSync(join(root, 'official/bin/cortico.mjs'), '');
    configure({source:join(root, 'official'),root});
    for (const path of ['data/plugin', 'workspace', 'worlds/custom']) mkdirSync(join(src,path),{recursive:true});
    writeJson(join(src, 'deployment.json'),{bot:'third-party-bot',version:'keep-me'});
    writeJson(join(src, '.manager.json'),{port:19001});
    const config = {displayName:'Source', paths:{memory:'workspace',data:'data'},web:{password:'source-secret',port:19001},worlds:{qq:{enabled:true,token:'fake-private-secret',wsUrl:'ws://localhost:1'},custom:{enabled:true,listenPort:1234,dbUrl:'postgres://private:secret@localhost/db'}}};
    writeJson(join(src,'config.json'),config);
    writeFileSync(join(src,'data/plugin/save.sqlite'),'synthetic game state');
    writeFileSync(join(src,'worlds/custom/other.bin'),'opaque data');
    writeFileSync(join(src,'workspace/note.md'),'memory');
    writeFileSync(join(src,'.env'),'PLUGIN_TOKEN=fake-env-secret\n');
    writeJson(join(src,'data/core-state.json'),{lastDeliveredCursor:7,persona:{notes:'keep'}});
    writeJson(join(src,'data/timers.json'),[{id:'timer'}]);
    for(const file of ['instance.lock','web-auth.key','.restart-request']) writeFileSync(join(src,'data',file),'source identity');
    symlinkSync(realpathSync(join(src,'workspace/note.md')),join(src,'worlds/custom/note-link'));
    const external=join(root,'external-data');mkdirSync(external);writeFileSync(join(external,'keep'),'external');
    symlinkSync(external,join(src,'external-link'));
    const input:CreateInput={id:'clone',name:'Clone',bot:'third-party-bot',source:'source',copyMode:'full',copy:EMPTY_COPY,allowStop:true};
    try {
        assert.match(inspectClone(home,'source').selectiveError,/copy-rules/);
        assert.equal(inspectClone(home,'source').fullError,'');
        assert.throws(()=>validateCreate(home,{...input,copyMode:'selective'}),/copy-rules/);
        const dst=await createSnapshot(home,input,19002);
        assert.equal(readFileSync(join(dst,'data/plugin/save.sqlite'),'utf8'),'synthetic game state');
        assert.equal(readFileSync(join(dst,'worlds/custom/other.bin'),'utf8'),'opaque data');
        assert.deepEqual(json(join(dst,'data/core-state.json')),json(join(src,'data/core-state.json')));
        assert.deepEqual(json(join(dst,'data/timers.json')),json(join(src,'data/timers.json')));
        assert.equal(readFileSync(join(dst,'.env'),'utf8'),'PLUGIN_TOKEN=fake-env-secret\n');
        assert.equal(json<any>(join(dst,'deployment.json')).version,'keep-me');
        for(const file of ['instance.lock','web-auth.key','.restart-request']) assert.equal(existsSync(join(dst,'data',file)),false);
        assert.equal(json<any>(join(dst,'config.json')).web.password,undefined);
        assert.equal(json<any>(join(dst,'.manager.json')).port,19002);
        assert.equal(resolve(join(dst,'worlds/custom'),readlinkSync(join(dst,'worlds/custom/note-link'))),join(dst,'workspace/note.md'));
        assert.equal(readlinkSync(join(dst,'external-link')),external);
        writeFileSync(join(dst,'worlds/custom/note-link'),'changed clone note');
        assert.equal(readFileSync(join(src,'workspace/note.md'),'utf8'),'memory');
        const review=cloneReview(home,'clone');
        assert.deepEqual(review.externalLinks,['external-link']);
        assert.deepEqual(review.worlds.find(w=>w.id==='custom')?.fields,['listenPort','dbUrl']);
        assert.ok(!JSON.stringify(review).includes('fake-private-secret'));
        assert.ok(!JSON.stringify(review).includes('fake-env-secret'));
        assert.ok(!JSON.stringify(review).includes('postgres://private'));
        setCloneWorldEnabled(home,'clone','qq',false);
        setCloneWorldEnabled(home,'clone','qq',true);
        assert.equal(cloneReview(home,'clone').worlds.find(w=>w.id==='qq')?.enabled,true);
        setCloneWorldEnabled(home,'clone','qq',false);
        assert.equal(cloneReview(home,'clone').worlds.find(w=>w.id==='qq')?.enabled,false);
        assert.deepEqual(json<any>(join(src,'config.json')),config);
        assert.equal(json<any>(join(dst,'config.json')).worlds.qq.token,'fake-private-secret');
        config.paths.data=external;writeJson(join(src,'config.json'),config);
        assert.match(inspectClone(home,'source').fullError,/paths.data/);
        await assert.rejects(createSnapshot(home,{...input,id:'outside'},19003),/paths.data/);
        assert.equal(existsSync(join(home,'outside')),false);
        config.paths.data='external-link/new-core-data';writeJson(join(src,'config.json'),config);
        assert.match(inspectClone(home,'source').fullError,/paths.data/);
    } finally {rmSync(root,{recursive:true,force:true});}
});
